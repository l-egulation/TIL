'''
"기준점으로부터의 절대적 거리" 계산

날짜 계산에서 "상대적인 차이(m1, m2 비교)"를 일일이 따지면 조건문(if-else)이 너무 복잡해짐
대신, 모든 날짜를 "2011년 1월 1일로부터 며칠째인가?"라는 하나의 숫자로 변환

계산 로직:
    1. 특정 날짜 (m, d)까지의 총 일수 = (1월부터 m-1월까지의 모든 일수 합) + 현재 날짜 d
    > ex. 2월 5일 -> 1월(31일) + 5일 = 36일째

    2. 차이 구하기
    > (두 번째 날짜의 총 일수) - (첫 번째 날짜의 총 일수) = 두 날짜 사이의 일수 차이(diff)
    > 결과가 양수(+)면 미래, 음수(-)면 과거를 의미

    3. 요일 결정:
    요일은 7일마다 반복되므로 (일수 차이 % 7)을 하면 요일 리스트의 인덱스를 얻을 수 있음
    % 연산자는 음수도 요일 순서에 맞게 처리해 주므로 과거 계산도 한 번에 해결
'''

# 두 날짜의 월, 일을 입력받음
m1, d1, m2, d2 = map(int, input().split())

# 요일 리스트 (문제에서 m1, d1이 월요일이므로 인덱스 0을 Mon으로 설정)
day_of_the_week = ['Mon', 'Tue', 'Wed', 'Thu', 'Fri', 'Sat', 'Sun']

# 각 달의 일수를 리스트로 만듦
# 인덱스 1이 1월이 되도록 맨 앞에 0을 넣어 칸을 맞춤
month_days = [0, 31, 28, 31, 30, 31, 30, 31, 31, 30, 31, 30, 31]

# 날짜를 "총 일수"로 바꿔주는 함수를 정의
def get_total_days(m, d):
    # m월 전까지(month_days[:m])의 일수를 모두 더하고(sum), 이번 달의 날짜(d)를 더함
    return sum(month_days[:m]) + d

# 두 날짜의 절대적인 위치 차이를 계산
# 미래라면 결과는 +, 과거라면 결과는 -
diff = get_total_days(m2, d2) - get_total_days(m1, d1)

# 7로 나눈 나머지를 이용해 요일 리스트에서 요일을 가져옴
# diff % 7의 원리:
# 1일 차이(나머지 1) -> Mon에서 한 칸 이동한 Tue
# -1일 차이(나머지 6) -> Mon에서 뒤로 한 칸 이동한 Sun (파이썬이 자동으로 계산)
print(day_of_the_week[diff % 7])