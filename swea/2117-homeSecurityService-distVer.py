'''
[초기 생각 및 로직 정리]
집의 수 = num

K**2 + (K-1)**2 <= M * num 을 항상 만족해야함
그리고 위 조건을 만족하는 가장 큰 num을 출력

K = 1 부터 차례대로
위치를 옮겨 가면서 탐색

## 의문점 1. 1(집)이 많은 곳을 어떻게 탐색하는가?
1이 많은 곳을 탐색한다는 것은 각 1 위치에서 delta로 탐색을 하든가 해서 인근의 1의 위치를 탐색한다는건데
사실상 이렇게 하기는 어려움
> 1을 시작점으로 하고, area에서 1의 위치를 탐색
> 찾은 1의 위치를 중심으로 홈 방법 서비스의 영역을 K = 1 ~ K = N 까지 늘리면서 다 조회해보나?
> K = N이면 전체 area가 꽉 참. 단, N이 홀수일 때만.

## 의문점 2. 범위 내의 집의 개수를 어떻게 셀 것인가?
마름모 형태의 범위를 순회하는 방법이 필요함
> 중심을 기준으로 depth = K-1 까지만 delta 탐색하기 > BFS?
> 그럼 BFS 인자로 K랑 위치 좌표만 주면 될 듯
> 그래서 범위 내에 있는 집의 수 num 출력

## 의문점 3. 완탐을 하면 시간초과가 발생할텐데, 어떻게 시간을 줄일 것인가?
일단 박고 시간초과나면 gemini
> 어느 K까지 해보고 그 뒤는 확인해볼 필요없어 라는 수학적 확신이 필요

--------------------------------------------------

# 1. 초기 로직 vs 최종 로직 비교 (Trial & Error)

(1) 탐색의 중심점:
    - 초기: "집이 있는 곳 위주로 탐색해야 효율적이지 않을까?" > 실패
    - 최종: 서비스 센터는 집이 없는 빈칸에도 설치될 수 있음. 모든 좌표(N*N) 전수 조사 필요

(2) 영역 탐색 방식:
    - 초기: BFS를 사용하여 K 단계만큼 확장하며 집을 카운트 > 비효율
        * 매번 visited 초기화 필요, 큐 연산 비용 발생, N^5에 가까운 복잡도로 TLE 위험
    - 최종: "마름모 = 맨해튼 거리(Manhattan Distance)" 공식 활용 > 최적화
        * 중심 (r, c)와 집 (hr, hc) 사이의 거리가 K 미만이면 방범 영역 안
        * |r - hr| + |c - hc| < K

(3) 데이터 구조 및 성능 최적화:
    - 초기: 매번 지도를 처음부터 끝까지 훑으며 집을 찾음.
    - 최종:
        1) 집의 위치를 미리 리스트(houses)에 저장하여 집이 없는 칸은 무시
        2) 거리별 빈도수 배열(dist_counts)을 사용해 K가 커질 때마다 누적합(O(1))으로 집의 개수를 업데이트

--------------------------------------------------

# 2. 셀프 피드백 (Self-Feedback)

- BFS가 무조건 정답은 아님
    격자판에서 마름모나 특정 거리 기반의 영역이 나오면 맨해튼 거리가 훨씬 빠를 수 있음

- 사소한 오타
    'if not visited[nr][nc]:'를 'if not visited:'로 적음

- 전처리(Pre-processing)
    지도 전체를 매번 뒤지는 것보다 필요한 데이터(집 위치)만 뽑아놓고 연산하는 것이 최적화의 핵심

'''

T = int(input())

for tc in range(1, T+1):
    N, M = map(int, input().split())
    area = [list(map(int, input().split())) for _ in range(N)]

    total_home_num = float('-inf')

    # 1. 전처리: 지도 전체를 뒤지는 대신, 집이 있는 좌표만 미리 리스트에 저장
    home_lst = []
    for r in range(N):
        for c in range(N):
            if area[r][c] == 1:
                home_lst.append((r, c))

    # 2. 모든 좌표(r, c)를 방범 서비스의 중심으로 가정하고 탐색 (N*N 반복)
    for r in range(N):
        for c in range(N):

            # 2-1. 특정 중심점에서 각 집까지의 거리 분포를 먼저 구함
            # dist_counts[d]: 현재 중심(r, c)에서 거리가 d인 집의 개수
            # 최대 거리는 (N-1) + (N-1)이므로 2*N 크기면 충분함
            dist_counts = [0] * (2*N)

            # 모든 집을 돌며 현재 중심점과의 거리를 계산 (집의 개수만큼 반복)
            for hr, hc in home_lst:
                dist = abs(r - hr) + abs(c - hc)
                dist_counts[dist] += 1

            # 2-2. K를 1부터 늘려가며 방범 영역에 포함되는 집을 누적으로 더함
            # > K를 1부터 늘려가며 방범 영역을 확장 (최대 2*N까지)
            # 현재 K 범위 안에 들어온 누적 집의 수
            home_num = 0

            # K는 지도를 다 덮을 때까지 (넉넉히 2*N)
            for k in range(1, N+2):

                # 거리가 k-1인 집들을 영역에 추가 (마름모가 한 칸 커지는 개념)
                home_num += dist_counts[k-1]

                # 운영 비용 계산식: K^2 + (K-1)^2
                cost = k*k + (k-1)*(k-1)

                # 수익(집 개수 * M)이 운영 비용보다 크거나 같다면 (손해가 없다면)
                if home_num * M >= cost:

                    # 그중에서 가장 많은 집을 포함하는 경우로 갱신
                    total_home_num = max(total_home_num, home_num)

    print(f'#{tc} {total_home_num}')