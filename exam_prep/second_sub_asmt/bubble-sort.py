N = int(input())
data = list(map(int, input().split()))

'''
🫧 버블 정렬(Bubble Sort)
버블 정렬은 '옆집'이랑만 비교해서 자리를 바꾸는 단순하고 정직한 정렬

비교(Compare): 인접한 두 숫자를 비교
교환(Swap): 왼쪽이 더 크면 자리를 바꿈
확정(Fix): 한 바퀴를 다 돌면 가장 큰 숫자가 맨 뒤로 감. 이 숫자는 이제 '확정' 되었으니 다음 바퀴부턴 신경 쓰지 않음

근데 왜 역순임?
> 정렬의 특정 :
> 첫 바퀴(Pass 1)가 끝나면 제일 큰 요소가 맨 뒤(N-1)에 고정
> 두 번째 바퀴가 끝나면 두 번째로 큰 요소가 N-2 자리에 고정

> 범위의 축소 : 이미 제 자리를 찾은 뒷부분은 다시 볼 필요가 없음

> 인덱스 에러 방지:
> 만약 i를 N-1로 잡으면, j는 0부터 N-2까지 돔
> 이때 j+1은 N-1이 되어 리스트의 마지막 인덱스를 안전하게 가리킴
> 만약 그냥 range(N)으로 돌리면 j+1이 N이 되어버려 리스트 밖을 건드림 > IndexError
'''

def bubble_sort(lst, N):
    # 1. 바깥쪽 루프 : 정렬할 범위를 뒤에서부터 하나씩 줄여나감
    # N-1부터 1까지 역순으로 가는 이유 : '비교할 끝 지점'을 정하기 위함
    for i in range(N-1, 0, -1):
        
        # 2. 안쪽 루프 : 실제로 옆집 숫자와 비교하며 전진
        # j는 0부터 i-1까지 움직임
        for j in range(i):
            
            # 3. 비교 : 왼쪽(j)이 오른쪽(j+1)보다 크면 자리를 바꿈
            # range(i)이므로 j의 최대값은 i-1
            # 따라서 j+1은 최대 i가 되어, '아직 정렬되지 않은 끝 칸'까지만 딱 건드림
            if lst[j] > lst[j+1]:
                # 4. 스왑(Swap) : 위치 교체
                lst[j], lst[j+1] = lst[j+1], lst[j]
                
    return lst
result = bubble_sort(N, data)
print(result)